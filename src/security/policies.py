def get_data_flow_diagram() -> str:
    """
    Generate a markdown data-flow diagram documenting what data
    enters and leaves each pipeline stage.
    """
    lines = ["# Privacy-Preserving Data Flow\n"]
    lines.append("| Stage | Data Enters | Data Leaves | Access | Identifier Handling |")
    lines.append("|-------|-------------|-------------|--------|---------------------|")
    for stage in DATA_FLOW_STAGES:
        lines.append(
            f"| {stage['stage']} | {stage['data_enters']} | "
            f"{stage['data_leaves']} | {stage['access']} | "
            f"{stage['identifier_handling']} |"
        )
    return "\n".join(lines)
